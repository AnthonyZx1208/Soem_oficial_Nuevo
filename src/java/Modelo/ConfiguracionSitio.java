package Modelo;

public class ConfiguracionSitio {

    private String nombreTienda;
    private String logoUrl;
    private String faviconUrl;
    private String colorPrimario;
    private String colorSecundario;
    private String colorAcento;
    private String contactoWhatsapp;
    private String contactoEmail;
    private String descripcionTienda;

    public String getNombreTienda() {
        return nombreTienda;
    }

    public void setNombreTienda(String nombreTienda) {
        this.nombreTienda = nombreTienda;
    }

    public String getLogoUrl() {
        return logoUrl;
    }

    public void setLogoUrl(String logoUrl) {
        this.logoUrl = logoUrl;
    }

    public String getFaviconUrl() {
        return faviconUrl;
    }

    public void setFaviconUrl(String faviconUrl) {
        this.faviconUrl = faviconUrl;
    }

    public String getColorPrimario() {
        return colorPrimario;
    }

    public void setColorPrimario(String colorPrimario) {
        this.colorPrimario = colorPrimario;
    }

    public String getColorSecundario() {
        return colorSecundario;
    }

    public void setColorSecundario(String colorSecundario) {
        this.colorSecundario = colorSecundario;
    }

    public String getColorAcento() {
        return colorAcento;
    }

    public void setColorAcento(String colorAcento) {
        this.colorAcento = colorAcento;
    }

    public String getContactoWhatsapp() {
        return contactoWhatsapp;
    }

    public void setContactoWhatsapp(String contactoWhatsapp) {
        this.contactoWhatsapp = contactoWhatsapp;
    }

    public String getContactoEmail() {
        return contactoEmail;
    }

    public void setContactoEmail(String contactoEmail) {
        this.contactoEmail = contactoEmail;
    }

    public String getDescripcionTienda() {
        return descripcionTienda;
    }

    public void setDescripcionTienda(String descripcionTienda) {
        this.descripcionTienda = descripcionTienda;
    }
}
